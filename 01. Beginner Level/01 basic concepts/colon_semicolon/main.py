# Colon in Python
# It is used to define a block of code
# =============================== Colon ==================================
if True:
    print("True")
else:
    print("False")


# Semicolon in Python
# It is used to separate multiple statements on the same line
# =============================== Semicolon ===============================
print("Hello"); print("World"); print("!")

# Better practice (without semicolon)
print("Hello", end=" ")
print("World")
print("!")

# =============================== comma ===============================
# Comma in Python
# It is used to separate multiple values in a single line
# =============================== comma ===============================
print("Hello", "World", "!")