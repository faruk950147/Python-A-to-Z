# ================================= What is scape Sequences ====================================
# Scape Sequences is a symbol that is used to perform scape sequences operations.
# new line character is \n
# tab character is \t
# backspace character is \b
# form feed character is \f
# backslash character is \\n
# 1. Example
# \n is a scape sequence
str1 = "Hello\nWorld"
print(f"1. it is a new line character: {str1}")
# \t is a scape sequence
str2 = "Hello\tWorld"
print(f"2. it is a tab character: {str2}")
# \r is a scape sequence
str3 = "Hello\rWorld"
print(f"3. it is a return character: {str3}")
# \b is a scape sequence
str4 = "Hello\bWorld"
print(f"4. it is a backspace character: {str4}")
# \f is a scape sequence
str5 = "Hello\fWorld"
print(f"5. it is a form feed character: {str5}")
# \\ is a scape sequence
str6 = "Hello\\World"
print(f"6. it is a backslash character: {str6}")
# \' is a scape sequence
str7 = "Hello\'World"
print(f"7. it is a single quote character: {str7}")
# \" is a scape sequence
str8 = "Hello\"World"
print(f"8. it is a double quote character: {str8}")
# \ is a scape sequence
str9 = "Hello\\World"
print(f"9. it is a backslash character: {str9}")

