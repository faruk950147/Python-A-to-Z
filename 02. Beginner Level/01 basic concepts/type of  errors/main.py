# ===================== type of errors ===================== 

# 1. Syntax Error
# 2. Runtime Error
# 3. Logical Error or semantic error
# ========================= syntax error =========================
# syntax error is a type of error that occurs when the code is not written in the correct syntax.
# print("Hello World) # syntax error because of missing closing quotation

# ========================= runtime error =========================
# runtime error is a type of error that occurs when the code is executed.
# print(10 / 0) # runtime error because of division by zero

# ========================= logical error =========================
# logical error is a type of error that occurs when the code is executed but the output is not as expected.
a = 10
b = 20
av = a + b / 3
# logical error because of we want to calculate the average of a and b but we are adding a and b and then dividing by 3
print(av) 

