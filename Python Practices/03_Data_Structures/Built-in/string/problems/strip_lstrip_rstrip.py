def strip_string(string):
    return string.strip()

print(strip_string("      Hello        "))


def lstrip_string(string):
    return string.lstrip()

print(lstrip_string("      Hello        "))


def rstrip_string(string):
    return string.rstrip()

print(rstrip_string("      Hello        "))


def strip_string(string, char):
    return string.strip(char)

print(strip_string("Hello", "l"))



