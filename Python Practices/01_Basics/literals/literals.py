# ============================= 12. Function Literal =============================
# Function literal is a value that is directly written into the source code.
def function1():
    print("Hello, World!")
function1()

# ============================= 13. Class Literal =============================
# Class literal is a value that is directly written into the source code.
class class1:
    def __init__(self):
        self.name = "John"
        self.age = 30
        self.city = "New York"
    def function1(self):
        print("Hello, World!")
class1 = class1()
class1.function1()


