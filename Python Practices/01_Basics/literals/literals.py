# ============================= 1. Literal =============================
# Literal is a value that is directly written into the source code.

# ============================= 2. String Literal =============================
# String literal is a value that is directly written into the source code.
string1 = "Hello, World!"
string2 = 'Hello, World!'
string3 = """Hello, World!"""
string4 = '''Hello, World!'''
print(string1)
print(string2)
print(string3)
print(string4)

# ============================= 3. Integer Literal =============================
# Integer literal is a value that is directly written into the source code.
integer1 = 10
integer2 = 0b1010
integer3 = 0o12
integer4 = 0x1A
print(integer1)
print(integer2)
print(integer3)
print(integer4)

