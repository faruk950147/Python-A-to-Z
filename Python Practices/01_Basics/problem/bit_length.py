def bit_length(num):
    return num.bit_length()

print('bit_length(5):', bit_length(5)) # Output: 3 bits because 5 in binary is 101
print('bit_length(10):', bit_length(10)) # Output: 4 bits because 10 in binary is 1010
print('bit_length(100):', bit_length(100)) # Output: 7 bits because 100 in binary is 1100100
