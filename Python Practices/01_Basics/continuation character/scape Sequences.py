# ================================= What is scape Sequences ====================================
# Scape Sequences is a symbol that is used to perform scape sequences operations.

# 1. Example
print("Hello World")
print("Hello World\n")
print("Hello World\t")
print("Hello World\r")
print("Hello World\b")
print("Hello World\f")
print("Hello World\\")
print("Hello World\'")
print("Hello World\"")

