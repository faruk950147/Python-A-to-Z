# =================== Complex ===================
# complex type is a numeric type it has only one value
# complex → a + bj where a and b are real numbers and j is the imaginary unit

# =================== Complex Example ===================
complex_num = 1 + 2j
print(type(complex_num)) # <class 'complex'>
print(complex_num) # (1+2j)

complex_num = 1 - 2j
print(type(complex_num)) # <class 'complex'>
print(complex_num) # (1-2j)

complex_num = 1j
print(type(complex_num)) # <class 'complex'>
print(complex_num) # 1j

complex_num = 1 + 2j
print(type(complex_num)) # <class 'complex'>
print(complex_num) # (1+2j)
