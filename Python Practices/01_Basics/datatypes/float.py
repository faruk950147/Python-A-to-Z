# =================== Float ===================
# it has limited length of digits (approximately 15–17 decimal digits)
# and a value range of about ±1.8 × 10^308
float = 1.e10 # float    → 1.e10, -5.e-10
print("float = 1.e10 # float    → 1.e10, -5.e-10\nprint(float) # 10000000000.0")
float = 1.e-10 # float    → 1.e10, -5.e-10
print("float = 1.e-10 # float    → 1.e10, -5.e-10\nprint(float) # 0.0000000001")
float = 3.14 # float    → 3.14, -0.5
print("float = 3.14 # float    → 3.14, -0.5\nprint(float) # 3.14")

# =================== Float Example ===================
num_float = 3.14 # float    → 3.14, -0.5
print(type(num_float)) # <class 'float'>
