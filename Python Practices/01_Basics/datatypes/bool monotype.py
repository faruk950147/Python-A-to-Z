
# =================== Boolean ===================
# boolean type is a binary type it has only two values
# bool → True, False or 0, 1 none zero any other value is True



# =================== Boolean Example ===================
is_active = True
print(type(is_active)) # <class 'bool'>
print(is_active) # True

is_active = False
print(type(is_active)) # <class 'bool'>
print(is_active) # False

is_active = 0
print(type(is_active)) # <class 'bool'>
print(is_active) # False

is_active = 1
print(type(is_active)) # <class 'bool'>
print(is_active) # True

is_active = 2
print(type(is_active)) # <class 'bool'>
print(is_active) # True

is_active = 3
print(type(is_active)) # <class 'bool'>
print(is_active) # True

# =================== NoneType ===================
# NoneType type is a null type it has only one value
# None

# =================== NoneType Example ===================
name = None
print(type(name)) # <class 'NoneType'>
print(name) # None

name = "John"
print(type(name)) # <class 'str'>
print(name) # John

name = 123
print(type(name)) # <class 'int'>
print(name) # 123
