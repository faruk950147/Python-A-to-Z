# abs function return absolute value without negative sign

# int absolute value
x = 2
y = 3

print(x) # 2
print(y) # 3

# float absolute value
a = 10.5
b = -10.5
print(abs(a)) # 10.5
print(abs(b)) # 10.5

# complex absolute value
# square root of a2 + b2 = c2  
z = 2 + 3j
print(abs(z)) # 3.605551275463989
