# IIFE (Immediately Invoked Function Expression)
# It is a function that is executed as soon as it is defined.
# It is a function that is executed as soon as it is defined.
# It is a function that is executed as soon as it is defined.

# ================================= IIFE with lambda function =================================
# Example
print((lambda x: x + 1)(2))

# Example 2
print((lambda x, y: x + y)(2, 3))

# ================================= IIFE with def function =================================
