# ============================= Intersection =============================
# Intersection is a set of all elements that are in both set A and set B.
# Intersection is a common element between set A and set B.
# Intersection is denoted by the symbol "∩".
a = {1, 2, 3}
b = {3, 4, 5}

print(a.intersection(b)) # {3}
print(a & b) # {3}